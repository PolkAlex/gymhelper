function findCatalog(name) {
    if (!name) return null;
    const low = String(name).toLowerCase();
    for (const c of CATALOG) if (c.n.toLowerCase() === low) return c;
    for (const c of CATALOG) if (low.startsWith(c.n.toLowerCase())) return c;
    return null;
}
function exMet(name) {
    const c = findCatalog(name);
    return c ? c.met : 4.0;
}
